    ff = f {1} ;
    slash = strfind (ff, '/') ;
    if (isempty (slash))
        slash = 1 ;
    else
        slash = slash (end) + 1 ;
    end
    o = ff (slash:end) ;
    % fprintf ('%s\n', o) ;
    variant_flags = '' ;
    variant_suffix = '' ;
    if (ismember (ff, klu_zlsrc))
        variant_flags = '-DCOMPLEX -DDLONG' ;
        variant_suffix = '_zl' ;
    elseif (ismember (ff, klu_lsrc))
        variant_flags = '-DDLONG' ;
        variant_suffix = '_l' ;
    end
